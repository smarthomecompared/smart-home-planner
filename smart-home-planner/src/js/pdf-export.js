async function _pdfDiagramPage(doc, data) {
    const bgFile = await getUiPreference('diagramBackground').catch(() => null);
    const hasBg  = bgFile && bgFile.path;
    const diagramDisplaySettings = await getUiPreference('diagramDisplaySettings').catch(() => null);
    const diagramAreaMode = _resolveDiagramAreaMode(diagramDisplaySettings);

    let rawPositions = {};
    try {
        rawPositions = hasBg
            ? (await window.loadMapImagePositions() || {})
            : (await window.loadMapPositions()      || {});
    } catch (_) {}

    if (!hasBg && rawPositions && typeof rawPositions === 'object') {
        const absolutePositions = {};
        Object.entries(rawPositions).forEach(([id, value]) => {
            if (!value || typeof value !== 'object') return;
            if (String(value.coordinateSpace || '') === 'background-normalized') return;
            const x = Number(value.x);
            const y = Number(value.y);
            if (!Number.isFinite(x) || !Number.isFinite(y)) return;
            absolutePositions[id] = value;
        });
        if (Object.keys(absolutePositions).length) {
            rawPositions = absolutePositions;
        }
    }

    const deviceMap     = new Map((data.devices || []).map(d => [String(d.id), d]));
    let positionedIds = Object.keys(rawPositions).filter(id => deviceMap.has(id));

    if (!hasBg && !positionedIds.length) return;

    // ── Pre-load background image once ────────────────────────────────────────
    let bgDataUrl = null;
    let bgImgType = 'JPEG';

    if (hasBg) {
        try {
            const url  = buildAppUrl('api/device-files/content')
                + '?path=' + encodeURIComponent(String(bgFile.path));
            const resp = await fetch(url);
            if (resp.ok) bgDataUrl = await _blobToDataUrl(await resp.blob());
        } catch (e) {
            console.warn('[pdf-export] Background load failed:', e.message);
        }
    }

    if (bgDataUrl) {
        const mimeMatch = bgDataUrl.match(/^data:(image\/[a-zA-Z+]+);/);
        const raw = (mimeMatch ? mimeMatch[1].split('/')[1] : 'jpeg').toUpperCase();
        bgImgType = raw === 'JPG' ? 'JPEG' : raw;
    }

    // ── Compute draw area (aspect-ratio preserving) ───────────────────────────
    const BASE_LAYOUT = {
        x: _PDF_MARGIN,
        y: _PDF_HEADER_H + 5,
        w: _PDF_CW,
        legendY: _PDF_FOOTER_Y - 14
    };
    BASE_LAYOUT.h = Math.max(140, BASE_LAYOUT.legendY - BASE_LAYOUT.y - 5);

    const CONN_LAYOUT = {
        x: 6,
        y: _PDF_HEADER_H + 2,
        w: _PDF_W - 12,
        legendY: _PDF_FOOTER_Y - 11
    };
    CONN_LAYOUT.h = Math.max(140, CONN_LAYOUT.legendY - CONN_LAYOUT.y - 4);
    let bgNaturalSize = null;

    const computeDrawRect = (layout) => {
        let drawX = layout.x;
        let drawY = layout.y;
        let drawW = layout.w;
        let drawH = layout.h;
        if (bgDataUrl) {
            try {
                const dims  = bgNaturalSize;
                if (dims) {
                    const ratio = dims.width / dims.height;
                    drawH = layout.w / ratio;
                    if (drawH > layout.h) {
                        drawH = layout.h;
                        drawW = layout.h * ratio;
                    }
                    drawX = layout.x + (layout.w - drawW) / 2;
                }
            } catch (_) {}
        }
        return { drawX, drawY, drawW, drawH };
    };

    if (bgDataUrl) {
        try {
            bgNaturalSize = await _imgNaturalSize(bgDataUrl);
        } catch (_) {
            bgNaturalSize = null;
        }
    }

    // ── Detect active connection types among positioned (non-wishlist) devices ─
    const validIds = positionedIds.filter(id => {
        const d = deviceMap.get(id);
        return d && d.status !== 'wishlist';
    });
    const posSet = new Set(validIds);

    const activeTypes = new Set();
    (data.devices || []).forEach(device => {
        if (!posSet.has(String(device.id))) return;
        if (Array.isArray(device.ports)) {
            device.ports.forEach(port => {
                if (!port.connectedTo || !posSet.has(String(port.connectedTo))) return;
                const kind = _pdfConnKind((port.type || '').split('-')[0]);
                if (kind) activeTypes.add(kind);
            });
        }
        if (device.wifiAccessPointId   && posSet.has(String(device.wifiAccessPointId)))   activeTypes.add('wifi');
        if (device.zigbeeParentId       && posSet.has(String(device.zigbeeParentId)))       activeTypes.add('zigbee');
        if (device.zwaveControllerId    && posSet.has(String(device.zwaveControllerId)))    activeTypes.add('zwave');
        if (device.bluetoothProxyId     && posSet.has(String(device.bluetoothProxyId)))     activeTypes.add('bluetooth');
    });

    // Order connection types: wired first, wireless last
    const typeOrder = ['ethernet', 'usb', 'hdmi', 'power', 'wifi', 'zigbee', 'zwave', 'bluetooth'];
    const connTypesToDraw = typeOrder.filter(t => activeTypes.has(t));

    // ── Render one page per diagram ───────────────────────────────────────────
    const _drawDiagramPage = (connType, heading) => {
        doc.addPage();
        _drawPageCanvas(doc);
        _drawPageHeader(doc, heading);

        doc.setFillColor(..._C.cardBg);
        doc.setDrawColor(..._C.cardBorder);
        doc.setLineWidth(0.25);
        const isOverview = connType === null;
        const layout = isOverview ? BASE_LAYOUT : CONN_LAYOUT;
        const drawRect = computeDrawRect(layout);

        doc.roundedRect(layout.x - 1.5, layout.y - 1.5, layout.w + 3, layout.h + 3, 3, 3, 'FD');

        if (bgDataUrl) {
            doc.addImage(bgDataUrl, bgImgType, drawRect.drawX, drawRect.drawY, drawRect.drawW, drawRect.drawH);
        }

        if (positionedIds.length) {
            const connectionStyle = _renderDiagramOverlay(
                doc,
                data,
                rawPositions,
                positionedIds,
                drawRect.drawX,
                drawRect.drawY,
                drawRect.drawW,
                drawRect.drawH,
                connType,
                isOverview,
                !!bgDataUrl,
                diagramAreaMode
            );
            if (isOverview) {
                // Status legend only — no connection lines
                _drawDiagramLegend(doc, layout.legendY, new Set(), connectionStyle, {
                    x: layout.x,
                    w: layout.w
                });
            } else {
                _drawDiagramLegend(doc, layout.legendY, new Set([connType]), connectionStyle, {
                    x: layout.x,
                    w: layout.w
                });
            }
        }
    };

    // Always render the overview first (all devices, no connections, no legend)
    _drawDiagramPage(null, 'Diagram — Overview');

    // Then one page per active connection type
    for (const connType of connTypesToDraw) {
        _drawDiagramPage(connType, `Network Diagram — ${_CONN_TYPE_LABELS[connType] || connType}`);
    }
}

